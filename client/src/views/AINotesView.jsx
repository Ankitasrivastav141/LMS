import React, { useState, useEffect } from 'react';
import { Sparkles, BookOpen, Search, Copy, Printer, Eye, ChevronRight } from 'lucide-react';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';
import { api } from '../api';

export default function AINotesView({ onSelectSubject }) {
  const [subjects, setSubjects] = useState([]);
  const [selectedSubjectId, setSelectedSubjectId] = useState('all');
  const [notes, setNotes] = useState([]);
  const [activeNote, setActiveNote] = useState(null);
  const [loading, setLoading] = useState(true);
  const [search, setSearch] = useState('');

  useEffect(() => {
    loadNotes();
  }, [selectedSubjectId]);

  const loadNotes = async () => {
    setLoading(true);
    try {
      const subs = await api.getSubjects();
      setSubjects(subs);

      const allNotes = [];
      const targetSubs = selectedSubjectId === 'all' ? subs : subs.filter((s) => s.id === selectedSubjectId);
      for (const s of targetSubs) {
        const nList = await api.getAINotes(s.id);
        nList.forEach((n) => {
          n.subject_name = s.name;
          n.subject_color = s.color;
        });
        allNotes.push(...nList);
      }
      setNotes(allNotes);
      if (allNotes.length > 0 && !activeNote) {
        setActiveNote(allNotes[0]);
      }
    } catch (err) {
      console.error('Error loading AI notes:', err);
    } finally {
      setLoading(false);
    }
  };

  const filteredNotes = notes.filter(
    (n) =>
      n.title.toLowerCase().includes(search.toLowerCase()) ||
      n.content.toLowerCase().includes(search.toLowerCase())
  );

  return (
    <div className="p-8 space-y-6 max-w-7xl mx-auto">
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-black text-[#191A23]">AI Learning Notes</h1>
          <p className="text-xs text-[#64748B] mt-0.5">
            Structured educational notes generated by Gemini directly from your lecture slides.
          </p>
        </div>
      </div>

      {/* Filter toolbar */}
      <div className="bg-white p-3.5 rounded-2xl border border-[#E8ECF2] shadow-xs flex flex-col sm:flex-row items-center justify-between gap-3">
        <div className="relative w-full sm:w-80">
          <Search className="w-4 h-4 text-[#94A3B8] absolute left-3.5 top-1/2 -translate-y-1/2" />
          <input
            type="text"
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            placeholder="Search notes content or titles..."
            className="w-full pl-9 pr-3 py-1.5 bg-[#F8F9FA] border border-[#E2E8F0] rounded-xl text-sm outline-none focus:border-[#E52521]"
          />
        </div>

        <div className="flex items-center gap-2 w-full sm:w-auto justify-end">
          <span className="text-xs font-semibold text-[#64748B]">Subject:</span>
          <select
            value={selectedSubjectId}
            onChange={(e) => setSelectedSubjectId(e.target.value)}
            className="bg-[#F8F9FA] border border-[#E2E8F0] text-xs font-semibold text-[#191A23] rounded-xl px-3 py-1.5 outline-none cursor-pointer"
          >
            <option value="all">All Subjects</option>
            {subjects.map((s) => (
              <option key={s.id} value={s.id}>
                {s.name}
              </option>
            ))}
          </select>
        </div>
      </div>

      {/* Main 2-column view */}
      {loading ? (
        <div className="p-16 text-center text-xs text-[#94A3B8] animate-pulse">Loading AI notes...</div>
      ) : filteredNotes.length === 0 ? (
        <div className="bg-white rounded-3xl border border-[#E8ECF2] p-16 text-center space-y-3">
          <Sparkles className="w-12 h-12 text-[#E52521]/30 mx-auto" />
          <h3 className="font-bold text-base text-[#191A23]">No AI notes available</h3>
          <p className="text-xs text-[#64748B] max-w-sm mx-auto">
            Open any subject, upload your lecture PPTs, and click "Generate AI Notes" to see comprehensive study guides here.
          </p>
        </div>
      ) : (
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 min-h-[600px]">
          {/* Notes sidebar */}
          <div className="lg:col-span-4 bg-white rounded-3xl border border-[#E8ECF2] shadow-xs p-5 space-y-3 flex flex-col">
            <h3 className="font-extrabold text-xs uppercase tracking-wider text-[#64748B]">
              Notes Directory ({filteredNotes.length})
            </h3>
            <div className="flex-1 overflow-y-auto space-y-2">
              {filteredNotes.map((n) => {
                const isSelected = activeNote?.id === n.id;
                return (
                  <div
                    key={n.id}
                    onClick={() => setActiveNote(n)}
                    className={`p-3.5 rounded-2xl border cursor-pointer transition-all ${
                      isSelected
                        ? 'bg-[#191A23] text-white border-[#191A23] shadow-xs'
                        : 'bg-[#F8F9FA] hover:bg-[#F1F5F9] border-[#E8ECF2] text-[#191A23]'
                    }`}
                  >
                    <span
                      className="text-[10px] font-bold px-2 py-0.5 rounded-full inline-block mb-1"
                      style={{
                        backgroundColor: isSelected ? 'rgba(255,255,255,0.15)' : '#FEE2E2',
                        color: isSelected ? '#FFFFFF' : '#E52521',
                      }}
                    >
                      {n.subject_name}
                    </span>
                    <h4 className="font-bold text-xs truncate">{n.title}</h4>
                    <p className={`text-[10px] mt-1 ${isSelected ? 'text-[#94A3B8]' : 'text-[#64748B]'}`}>
                      Version {n.version} • {new Date(n.updated_at).toLocaleDateString()}
                    </p>
                  </div>
                );
              })}
            </div>
          </div>

          {/* Reader Area */}
          <div className="lg:col-span-8 bg-white rounded-3xl border border-[#E8ECF2] shadow-xs flex flex-col overflow-hidden">
            {activeNote ? (
              <>
                <div className="p-5 border-b border-[#F1F5F9] bg-[#FFFDF9] flex items-center justify-between gap-4">
                  <div>
                    <span className="text-[10px] font-bold text-[#E52521] uppercase tracking-wider">
                      {activeNote.subject_name}
                    </span>
                    <h2 className="font-black text-xl text-[#191A23]">{activeNote.title}</h2>
                  </div>

                  <div className="flex items-center gap-2">
                    <button
                      onClick={() => onSelectSubject(activeNote.subject_id, 'ai-notes')}
                      className="px-3 py-1.5 bg-[#F8F9FA] hover:bg-[#E2E8F0] border border-[#E2E8F0] rounded-xl text-xs font-bold text-[#191A23]"
                    >
                      Open Subject Workspace &rarr;
                    </button>
                    <button
                      onClick={() => {
                        navigator.clipboard.writeText(activeNote.content);
                        alert('Copied to clipboard!');
                      }}
                      className="p-2 bg-white hover:bg-[#F1F5F9] border border-[#E2E8F0] rounded-xl text-[#64748B]"
                      title="Copy"
                    >
                      <Copy className="w-4 h-4" />
                    </button>
                    <button
                      onClick={() => window.print()}
                      className="p-2 bg-white hover:bg-[#F1F5F9] border border-[#E2E8F0] rounded-xl text-[#64748B]"
                      title="Print / PDF"
                    >
                      <Printer className="w-4 h-4" />
                    </button>
                  </div>
                </div>

                <div className="p-8 flex-1 overflow-y-auto">
                  <div className="prose prose-slate max-w-none prose-headings:font-black prose-headings:text-[#191A23] prose-p:text-[#334155] prose-li:text-[#334155] prose-table:border prose-table:border-[#E2E8F0] prose-th:bg-[#F8F9FA] prose-th:p-3 prose-td:p-3 prose-td:border prose-td:border-[#E2E8F0]">
                    <ReactMarkdown remarkPlugins={[remarkGfm]}>{activeNote.content}</ReactMarkdown>
                  </div>
                </div>
              </>
            ) : null}
          </div>
        </div>
      )}
    </div>
  );
}
